-- [dock id] = route ids that call there, sorted.
ns.RoutesAtDock = {}
for routeID, route in pairs(ns.Routes) do
	for _, dockID in ipairs(route.stops) do
		local list = ns.RoutesAtDock[dockID]
		if not list then
			list = {}
			ns.RoutesAtDock[dockID] = list
		end
		list[#list + 1] = routeID
	end
end
for _, list in pairs(ns.RoutesAtDock) do
	table.sort(list)
end
